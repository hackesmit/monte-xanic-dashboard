-- migration_mona_uso_reserva.sql — token budget reserved before /api/mona calls
-- Anthropic, reconciled after (xd-aiz round 2).
--
-- migration_mona_uso counted tokens only after a stream ended, so N requests
-- opened at once all saw tokens = 0 and were all admitted: the token cap did
-- not cover requests in flight, and a failed write after the stream left the
-- spend uncharged for good. Now each request reserves its worst case up front
-- (input estimate plus max_tokens) under the user's row lock, the pending
-- reservations count against the cap, and the reservation is released only by
-- a confirmed reconciliation that charges what the stream used. A reservation
-- whose reconciliation never lands stays held, so a lost write costs the
-- conservative estimate, never zero. It is held for its own day only: the cap
-- is per day (America/Tijuana), so a stuck reservation stops counting at
-- midnight and needs no sweeper.

ALTER TABLE public.mona_uso
  ADD COLUMN IF NOT EXISTS tokens_reservados bigint NOT NULL DEFAULT 0;

-- One row per admitted request. id is generated by api/mona.js; it makes both
-- the reservation and the reconciliation idempotent, so either can be retried.
-- cobrado is NULL while the request is open (or its reconciliation was lost).
CREATE TABLE IF NOT EXISTS public.mona_uso_reserva (
  id           uuid        PRIMARY KEY,
  username     text        NOT NULL,
  dia          date        NOT NULL,
  reservado    bigint      NOT NULL CHECK (reservado >= 0),
  cobrado      bigint      CHECK (cobrado >= 0),
  creado       timestamptz NOT NULL DEFAULT now(),
  reconciliado timestamptz,
  FOREIGN KEY (username, dia) REFERENCES public.mona_uso (username, dia)
);

ALTER TABLE public.mona_uso_reserva ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.mona_uso_reserva FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.mona_uso_reserva TO service_role;

-- The round-1 pair (reserve a request, add tokens afterwards) is replaced.
-- Nothing in production calls it: it shipped only on the unmerged xd-aiz branch.
DROP FUNCTION IF EXISTS public.mona_uso_reservar(text, integer, bigint);
DROP FUNCTION IF EXISTS public.mona_uso_sumar_tokens(text, date, bigint);

-- Reserve one request and p_tokens of budget for p_username today. The FOR
-- UPDATE lock on the user's day row serialises concurrent calls, and the check
-- counts tokens spent plus tokens held by open requests plus this request, so
-- N parallel requests admit exactly the ones whose worst case fits. Calling it
-- again with the same p_id returns the first answer and reserves nothing more.
-- Returns { permitido, dia, peticiones, tokens, tokens_reservados }.
CREATE OR REPLACE FUNCTION public.mona_uso_reservar(
  p_id uuid, p_username text, p_tokens bigint, p_max_peticiones integer, p_max_tokens bigint
) RETURNS jsonb
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_dia date := (now() AT TIME ZONE 'America/Tijuana')::date;
  v_row public.mona_uso%ROWTYPE;
  v_prev public.mona_uso_reserva%ROWTYPE;
BEGIN
  IF p_id IS NULL OR p_username IS NULL OR p_username = '' THEN
    RAISE EXCEPTION 'mona_uso_reservar: id y username requeridos';
  END IF;
  IF p_tokens IS NULL OR p_tokens < 0 THEN
    RAISE EXCEPTION 'mona_uso_reservar: tokens invalidos';
  END IF;

  INSERT INTO public.mona_uso (username, dia) VALUES (p_username, v_dia)
    ON CONFLICT (username, dia) DO NOTHING;
  SELECT * INTO v_row FROM public.mona_uso u
   WHERE u.username = p_username AND u.dia = v_dia FOR UPDATE;

  SELECT * INTO v_prev FROM public.mona_uso_reserva r WHERE r.id = p_id;
  IF FOUND THEN
    IF v_prev.username <> p_username THEN
      RAISE EXCEPTION 'mona_uso_reservar: id de otra cuenta';
    END IF;
    RETURN jsonb_build_object('permitido', true, 'dia', v_prev.dia,
      'peticiones', v_row.peticiones, 'tokens', v_row.tokens,
      'tokens_reservados', v_row.tokens_reservados);
  END IF;

  IF v_row.peticiones >= p_max_peticiones
     OR v_row.tokens + v_row.tokens_reservados + p_tokens > p_max_tokens THEN
    RETURN jsonb_build_object('permitido', false, 'dia', v_dia,
      'peticiones', v_row.peticiones, 'tokens', v_row.tokens,
      'tokens_reservados', v_row.tokens_reservados);
  END IF;

  UPDATE public.mona_uso u
     SET peticiones = u.peticiones + 1,
         tokens_reservados = u.tokens_reservados + p_tokens,
         actualizado = now()
   WHERE u.username = p_username AND u.dia = v_dia
  RETURNING u.* INTO v_row;
  INSERT INTO public.mona_uso_reserva (id, username, dia, reservado)
    VALUES (p_id, p_username, v_dia, p_tokens);

  RETURN jsonb_build_object('permitido', true, 'dia', v_dia,
    'peticiones', v_row.peticiones, 'tokens', v_row.tokens,
    'tokens_reservados', v_row.tokens_reservados);
END;
$$;

-- Close reservation p_id: charge p_tokens to its day and release what it held.
-- Idempotent: only the first call for an id moves the counters; a retry after a
-- lost response returns { reconciliado: true, nuevo: false }. An unknown id is
-- an error, so a typo never reads as "settled".
CREATE OR REPLACE FUNCTION public.mona_uso_reconciliar(
  p_id uuid, p_tokens bigint
) RETURNS jsonb
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_res public.mona_uso_reserva%ROWTYPE;
  v_cobro bigint := GREATEST(COALESCE(p_tokens, 0), 0);
BEGIN
  UPDATE public.mona_uso_reserva r
     SET cobrado = v_cobro, reconciliado = now()
   WHERE r.id = p_id AND r.cobrado IS NULL
  RETURNING r.* INTO v_res;

  IF NOT FOUND THEN
    IF EXISTS (SELECT 1 FROM public.mona_uso_reserva r WHERE r.id = p_id) THEN
      RETURN jsonb_build_object('reconciliado', true, 'nuevo', false);
    END IF;
    RAISE EXCEPTION 'mona_uso_reconciliar: reserva desconocida %', p_id;
  END IF;

  UPDATE public.mona_uso u
     SET tokens = u.tokens + v_cobro,
         tokens_reservados = GREATEST(u.tokens_reservados - v_res.reservado, 0),
         actualizado = now()
   WHERE u.username = v_res.username AND u.dia = v_res.dia;

  RETURN jsonb_build_object('reconciliado', true, 'nuevo', true);
END;
$$;

REVOKE ALL ON FUNCTION public.mona_uso_reservar(uuid, text, bigint, integer, bigint) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.mona_uso_reconciliar(uuid, bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.mona_uso_reservar(uuid, text, bigint, integer, bigint) TO service_role;
GRANT EXECUTE ON FUNCTION public.mona_uso_reconciliar(uuid, bigint) TO service_role;

INSERT INTO public.applied_migrations (name) VALUES ('migration_mona_uso_reserva')
  ON CONFLICT (name) DO NOTHING;
